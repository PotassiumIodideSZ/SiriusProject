def seed():
    print("Updating Survey Questions...")
    # Clear existing answers, questionnaires and questions
    from surveys.models import QuestionAnswer, Questionnaire
    QuestionAnswer.objects.all().delete()
    Questionnaire.objects.all().delete()
    SurveyQuestion.objects.all().delete()
    
    for q in QUESTIONS:
        SurveyQuestion.objects.create(
            order=q['order'],
            category=q['category'],
            text=q['text'],
            options=q['options'],
            is_enabled=True
        )
        print(f"  + Added Q{q['order']}: {q['text'][:55]}... ({len(q['options'])} options)")
        
    print(f"\nDone! Seeded {len(QUESTIONS)} modern behavioral questions.")

if __name__ == '__main__':
    seed()
